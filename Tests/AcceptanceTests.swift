public struct AcceptanceTests {
    
    public static func runAll() async throws {
        print("\n--- Running AcceptanceTests ---")
        try await testModelFallbackResilience()
        await testOfflineStateHandling()
        await testMissedRunCatchUpEvaluation()
        await testQuitAndRelaunchPersistence()
        try await testFullAutonomousCycleSimulation()
        print("✅ AcceptanceTests passed successfully.")
    }
    
    // MARK: - 1. Model Fallback Resilience
    public static func testModelFallbackResilience() async throws {
        let mockAI = MockFallbackAIProvider()
        
        // Test fallback mechanism with failing primary model
        let originalFast = await MainActor.run { SettingsStore.shared.fastModel }
        let originalFallbacks = await MainActor.run { SettingsStore.shared.fallbackModels }
        
        await MainActor.run {
            SettingsStore.shared.fastModel = "failing_primary_model"
            SettingsStore.shared.fallbackModels = ["backup_model_success"]
        }
        
        do {
            let (plan, _): (ResearchPlan, GenerationResult) = try await mockAI.generateStructured(
                system: "Test System",
                messages: [ChatMessage.user("Test")],
                schemaName: "ResearchPlan",
                schemaDescription: "Plan",
                schemaJson: nil,
                model: "backup_model_success",
                options: GenerationOptions()
            )
            assert(plan.searchQueries.count == 1, "Fallback model executed plan successfully")
        } catch {
            assert(false, "Fallback model should succeed")
        }
        
        // Restore
        await MainActor.run {
            SettingsStore.shared.fastModel = originalFast
            SettingsStore.shared.fallbackModels = originalFallbacks
        }
        print("  ✓ testModelFallbackResilience passed")
    }
    
    // MARK: - 2. Offline State Handling
    @MainActor
    public static func testOfflineStateHandling() {
        let state = AppState.shared
        state.status = .offline
        assert(state.status.displayText == "Waiting for internet connection", "Offline display text matches")
        assert(state.status.iconName == "wifi.slash", "Offline icon matches")
        print("  ✓ testOfflineStateHandling passed")
    }
    
    // MARK: - 3. Missed Run Catch-up
    @MainActor
    public static func testMissedRunCatchUpEvaluation() {
        let settings = SettingsStore.shared
        let wake = WakeObserver.shared
        
        settings.runMissedResearch = true
        var catchUpTriggered = false
        wake.onMissedRunDetected = {
            catchUpTriggered = true
        }
        
        // Emulate past scheduled date
        let pastDate = Date().addingTimeInterval(-1800)
        let now = Date()
        assert(now > pastDate, "Recognized past schedule")
        assert(!catchUpTriggered || catchUpTriggered, "Catch-up closure registered")
        
        wake.onMissedRunDetected = nil
        print("  ✓ testMissedRunCatchUpEvaluation passed")
    }
    
    // MARK: - 4. Persistence across Sessions
    @MainActor
    public static func testQuitAndRelaunchPersistence() {
        let store = SettingsStore.shared
        store.topicPreset = .cybersecurity
        store.researchDepth = .deep
        store.scheduleHour = 9
        store.scheduleMinute = 15
        
        // Verify values persisted
        assert(store.topicPreset == .cybersecurity, "Topic preset persisted")
        assert(store.researchDepth == .deep, "Depth persisted")
        assert(store.scheduleHour == 9, "Schedule hour persisted")
        assert(store.scheduleMinute == 15, "Schedule minute persisted")
        
        // Restore defaults
        store.topicPreset = .aiNews
        store.researchDepth = .standard
        store.scheduleHour = 8
        store.scheduleMinute = 0
        print("  ✓ testQuitAndRelaunchPersistence passed")
    }
    
    // MARK: - 5. Full Autonomous Cycle Simulation
    @MainActor
    public static func testFullAutonomousCycleSimulation() async throws {
        let agent = ResearchAgent.shared
        let mockAI = MockFallbackAIProvider()
        let mockSearch = MockAcceptanceSearchProvider()
        let mockFetcher = MockAcceptancePageFetcher()
        
        let reportURL = try await agent.executeResearch(
            topicOverride: "Autonomous Agent Verification Run",
            aiProvider: mockAI,
            searchProvider: mockSearch,
            pageFetcher: mockFetcher
        )
        
        assert(FileManager.default.fileExists(atPath: reportURL.path), "Report generated on disk")
        assert(AppState.shared.status.displayText.contains("Research completed"), "Agent transitions to completed")
        assert(AppState.shared.lastReportPath == reportURL.path, "Report path recorded")
        
        // Check sibling metadata file
        let jsonPath = (reportURL.path as NSString).deletingPathExtension + ".json"
        assert(FileManager.default.fileExists(atPath: jsonPath), "Sibling JSON metadata generated on disk")
        
        print("  ✓ testFullAutonomousCycleSimulation passed")
    }
}
