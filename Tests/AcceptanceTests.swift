import PersonalResearchAgentCore

// MARK: - Mock Fallback Model AI Provider
private final class MockFallbackAIProvider: AIProvider, @unchecked Sendable {
    var primaryModelCalled = false
    var fallbackModelCalled = false
    
    func generate(
        system: String,
        messages: [ChatMessage],
        model: String?,
        options: GenerationOptions
    ) async throws -> GenerationResult {
        if model == "failing_primary_model" {
            primaryModelCalled = true
            throw AIProviderError.modelUnavailable(model: "failing_primary_model", reason: "Model 404 Not Found")
        }
        fallbackModelCalled = true
        return GenerationResult(
            text: "# Sourced Report\n\nGenerated by fallback model successfully.\n\n## Sources\n- [Valid](https://example.com/source)",
            modelUsed: model ?? "fallback_model"
        )
    }
    
    func generateStructured<T: Decodable>(
        system: String,
        messages: [ChatMessage],
        schemaName: String?,
        schemaDescription: String?,
        schemaJson: [String: Any]?,
        model: String?,
        options: GenerationOptions
    ) async throws -> (data: T, result: GenerationResult) {
        if model == "failing_primary_model" {
            primaryModelCalled = true
            throw AIProviderError.modelUnavailable(model: "failing_primary_model", reason: "Model 404 Not Found")
        }
        fallbackModelCalled = true
        if schemaName == "ResearchPlan" {
            let plan = ResearchPlan(subQuestions: ["SubQ 1"], searchQueries: ["Query 1"])
            return (plan as! T, GenerationResult(text: "{}", modelUsed: model ?? "fallback_model"))
        } else if schemaName == "ExtractionResponse" {
            let resp = ExtractionResponse(extractedFacts: [ExtractedFact(claim: "Fact 1", sourceUrl: "https://example.com/source")])
            return (resp as! T, GenerationResult(text: "{}", modelUsed: model ?? "fallback_model"))
        }
        throw AIProviderError.parsingFailed("Unknown schema")
    }
}

